import { NextResponse } from "next/server";
import { getSessionOrg } from "@/lib/session";
import { prisma, invoiceInterest, daysOverdue } from "@/lib/recovery";
import { loadInvoice } from "@/lib/dto";

/**
 * GET /api/samadhaan/[invoiceId] — generates a pre-filled MSEFC Form-A
 * application for filing on the MSME Samadhaan portal (samadhaan.msme.gov.in).
 */
export async function GET(req: Request, ctx: { params: Promise<{ invoiceId: string }> }) {
  const org = await getSessionOrg();
  if (!org) return NextResponse.json({ error: "No session" }, { status: 401 });
  const { invoiceId } = await ctx.params;

  const inv = await loadInvoice(org.id, invoiceId);
  if (!inv) return NextResponse.json({ error: "Invoice not found" }, { status: 404 });

  const now = new Date();
  const od = daysOverdue({ dueOn: inv.dueOn }, now);
  const { interest, totalDue, annualPct } = invoiceInterest(inv.amount, inv.dueOn, now);
  const fmtDate = (d: Date) => d.toLocaleDateString("en-IN", { day: "2-digit", month: "long", year: "numeric" });

  const form = [
    `APPLICATION UNDER SECTION 18 OF THE MSMED ACT, 2006`,
    `(To be filed before the Micro and Small Enterprises Facilitation Council)`,
    ``, `FORM-A`, ``,
    `1. NAME OF THE SUPPLIER (APPLICANT): ${org.name}`,
    `2. ADDRESS: ${org.city ?? "—"}, India`,
    `3. GSTIN: ${org.gstin ?? "—"}`,
    `4. NATURE OF BUSINESS: Manufacturing/Service (MSME)`,
    ``, `6. NAME OF THE BUYER (RESPONDENT): ${inv.buyer.name}`,
    `7. BUYER GSTIN: ${inv.buyer.gstin ?? "—"}`,
    ``, `9. INVOICE DETAILS:`,
    `   Invoice Number: ${inv.number}`,
    `   Invoice Date: ${fmtDate(inv.issuedOn)}`,
    `   Amount: Rs. ${Math.round(inv.amount).toLocaleString("en-IN")}/-`,
    `   Due Date (§15, 45 days): ${fmtDate(inv.dueOn)}`,
    `   Days Overdue: ${od} days`,
    ``, `10. AMOUNT CLAIMED:`,
    `   Principal: Rs. ${Math.round(inv.amount).toLocaleString("en-IN")}/-`,
    `   §16 Compound Interest (${annualPct.toFixed(2)}% p.a.): Rs. ${Math.round(interest).toLocaleString("en-IN")}/-`,
    `   TOTAL CLAIMED: Rs. ${Math.round(totalDue).toLocaleString("en-IN")}/-`,
    ``, `11. NATURE OF CLAIM: Non-payment of consideration for goods/services supplied`,
    `    contrary to Section 15 of the MSMED Act, 2006. Compound interest under`,
    `    Section 16 + tax deduction disallowed under Section 43B(h) of the IT Act.`,
    ``, `12. EVIDENCE ENCLOSED:`,
    `   [✓] Tax invoice (GST compliant)`,
    `   [✓] Purchase order / work order`,
    `   [✓] Delivery challan + e-way bill`,
    `   [✓] GSTR-1 extract (filed)`,
    `   [✓] Buyer ledger statement`,
    `   [✓] Statutory demand notice served under §15/§16`,
    ``, `13. RELIEF SOUGHT:`,
    `   (a) A decree for Rs. ${Math.round(totalDue).toLocaleString("en-IN")}/-`,
    `   (b) Directions to the buyer to pay within 90 days (§18(2))`,
    `   (c) Deposit of 75% of the decree amount before any appeal (§19)`,
    ``, `Date: ${fmtDate(now)}`, `Place: ${org.city ?? "—"}`,
    ``, `(Signature of the Supplier / Authorised Representative)`,
    `Name: ${org.name}`,
    ``, `---`, `Generated by Recovery OS on ${fmtDate(now)}.`,
    `File online at: https://samadhaan.msme.gov.in`,
  ].join("\n");

  return new NextResponse(form, {
    status: 200,
    headers: {
      "Content-Type": "text/plain; charset=utf-8",
      "Content-Disposition": `inline; filename="MSEFC-Form-A-${inv.number}.txt"`,
      "Cache-Control": "no-store",
    },
  });
}
